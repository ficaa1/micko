// Builds site/screens.js from site/screens/*.ans (tmux capture-pane -e):
//   window.SKINS[name]   = { bg, text, ... } from internal/ui/shared/skins.go
//   window.SCREENS[name] = { skin, rows: [[ [text, fg, bg, flags], ... ], ...] }
//   window.SEQS[name]    = [[seconds, frameName], ...] for an animation
// A screen's skin is in its name (skin_X), else monokai.
// flags: 1 bold, 2 faint, 4 italic, 8 underline. fg/bg null = the skin's default.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const skinsGo = fs.readFileSync(path.resolve(here, '../internal/ui/shared/skins.go'), 'utf8');

const skins = {};
for (const m of skinsGo.matchAll(/"([a-z-]+)":\s*\{(true|false),\s*palette\{([^}]*)\}/g)) {
  const p = { dark: m[2] === 'true' };
  for (const kv of m[3].matchAll(/(\w+):\s*"(#[0-9a-fA-F]{6})"/g)) p[kv[1]] = kv[2];
  skins[m[1]] = p;
}

const ansi16 = ['#15161e', '#f7768e', '#9ece6a', '#e0af68', '#7aa2f7', '#bb9af7', '#7dcfff', '#a9b1d6',
  '#414868', '#f7768e', '#9ece6a', '#e0af68', '#7aa2f7', '#bb9af7', '#7dcfff', '#c0caf5'];
const hex = (r, g, b) => '#' + [r, g, b].map((v) => (+v).toString(16).padStart(2, '0')).join('');
function xterm256(n) {
  if (n < 16) return ansi16[n];
  if (n < 232) { n -= 16; const c = [0, 95, 135, 175, 215, 255]; return hex(c[Math.floor(n / 36)], c[Math.floor(n / 6) % 6], c[n % 6]); }
  const v = 8 + (n - 232) * 10; return hex(v, v, v);
}

const COLS = 124;

function parse(src) {
  let fg = null, bg = null, fl = 0;
  const rows = [];
  for (let line of src.replace(/\n$/, '').split('\n')) {
    // tmux writes some runs of blank cells as tabs; pad them back to the pane width.
    if (line.includes('\t')) {
      const missing = COLS - [...line.replace(/\x1b\[[0-9;]*m/g, '').replace(/\t/g, '')].length;
      line = line.replace('\t', ' '.repeat(Math.max(missing, 0))).replace(/\t/g, '');
    }
    const runs = [];
    let buf = '';
    const flush = () => {
      if (!buf) return;
      const last = runs[runs.length - 1];
      if (last && last[1] === fg && last[2] === bg && last[3] === fl) last[0] += buf;
      else runs.push([buf, fg, bg, fl]);
      buf = '';
    };
    const re = /\x1b\[([0-9;]*)m|([^\x1b]+)/g;
    let m;
    while ((m = re.exec(line))) {
      if (m[2] !== undefined) { buf += m[2]; continue; }
      flush();
      const a = (m[1] || '0').split(';').map(Number);
      for (let i = 0; i < a.length; i++) {
        const c = a[i];
        if (c === 0) { fg = bg = null; fl = 0; }
        else if (c === 1) fl |= 1; else if (c === 2) fl |= 2; else if (c === 3) fl |= 4; else if (c === 4) fl |= 8;
        else if (c === 22) fl &= ~3; else if (c === 23) fl &= ~4; else if (c === 24) fl &= ~8;
        else if (c === 39) fg = null; else if (c === 49) bg = null;
        else if (c === 38 || c === 48) {
          let col;
          if (a[i + 1] === 2) { col = hex(a[i + 2], a[i + 3], a[i + 4]); i += 4; }
          else { col = xterm256(a[i + 2]); i += 2; }
          if (c === 38) fg = col; else bg = col;
        }
        else if (c >= 30 && c <= 37) fg = ansi16[c - 30]; else if (c >= 90 && c <= 97) fg = ansi16[c - 82];
        else if (c >= 40 && c <= 47) bg = ansi16[c - 40]; else if (c >= 100 && c <= 107) bg = ansi16[c - 92];
      }
    }
    flush();
    rows.push(runs);
  }
  return rows;
}

const dir = path.join(here, 'screens');
const screens = {}, seqs = {};
for (const f of fs.readdirSync(dir).sort()) {
  const full = path.join(dir, f);
  if (f.endsWith('.seq')) {
    seqs[f.slice(0, -4)] = fs.readFileSync(full, 'utf8').trim().split('\n').map((l) => { const [t, fr] = l.split(' '); return [+t, fr]; });
  } else if (f.endsWith('.ans')) {
    const name = f.slice(0, -4);
    screens[name] = { skin: (name.match(/^skin_(.+)$/) || [])[1] || 'monokai', rows: parse(fs.readFileSync(full, 'utf8')) };
  }
}
const used = {};
for (const s of Object.values(screens)) used[s.skin] = skins[s.skin];
fs.writeFileSync(path.join(here, 'screens.js'), '// Generated by site/screens.mjs from site/screens/. Do not edit.\n' +
  'window.SKINS = ' + JSON.stringify(used) + ';\n' +
  'window.SCREENS = ' + JSON.stringify(screens) + ';\n' +
  'window.SEQS = ' + JSON.stringify(seqs) + ';\n');
console.log(`wrote site/screens.js: ${Object.keys(screens).length} screens`);
